#!/usr/bin/env python3
"""Generate Xcode's ignored local configuration from .env without executing it."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
PATTERNS = {
    'DEVELOPMENT_TEAM': r'[A-Z0-9]{10}',
    'NOTED_BUNDLE_ID': r'[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+',
    'NOTED_APP_GROUP_ID': r'group\.[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+',
    'APPLE_ID': r'[^\s@]+@[^\s@]+',
    'IPHONE_UDID': r'[A-Za-z0-9-]+',
}


def main():
    source = ROOT / '.env'
    if not source.exists():
        sys.exit('Copy .env.example to .env and fill in your local values first.')
    values = {}
    for number, line in enumerate(source.read_text().splitlines(), 1):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        key, separator, value = line.partition('=')
        key, value = key.strip(), value.strip()
        if not separator or key not in PATTERNS or key in values:
            sys.exit(f'Invalid or duplicate .env key on line {number}.')
        if not re.fullmatch(PATTERNS[key], value):
            sys.exit(f'Invalid value for {key} on line {number}.')
        values[key] = value
    settings = ('DEVELOPMENT_TEAM', 'NOTED_BUNDLE_ID', 'NOTED_APP_GROUP_ID')
    if any(key not in values for key in settings):
        sys.exit('Missing required signing or bundle configuration in .env.')
    target = ROOT / 'Config' / 'Local.xcconfig'
    target.write_text('// Generated by scripts/configure-env.py; edit .env instead.\n'
                      + ''.join(f'{key} = {values[key]}\n' for key in settings))
    target.chmod(0o600)
    print('Updated Config/Local.xcconfig from .env (account and device stay local).')


if __name__ == '__main__':
    main()
